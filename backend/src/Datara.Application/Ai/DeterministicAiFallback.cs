using System.Globalization;
using Datara.Application.Analysis;

namespace Datara.Application.Ai;

/// <summary>
/// The rule-based half of Datara AI.
///
/// Every value it reports is read directly from the profile, so its output is
/// factual by construction. It serves two purposes: it makes the product fully
/// usable with no API key, and it guarantees the "facts" list in a model answer is
/// always calculated rather than hallucinated.
/// </summary>
public sealed class DeterministicAiFallback : IDeterministicAiFallback
{
    public AiDatasetSummary BuildSummary(DatasetProfileResponse profile, string datasetName)
    {
        var stats = BuildStatisticsNarrative(profile);
        var readiness = profile.MlReadiness;

        var summary =
            $"{N0(profile.RowCount)} rows and {N0(profile.ColumnCount)} columns "
            + $"({DescribeComposition(profile)}). "
            + stats
            + (readiness is null
                ? string.Empty
                : $" ML readiness scores {I0(readiness.Overall)}/100 ({readiness.Grade}). "
                  + readiness.Verdict);

        var facts = BuildCoreFacts(profile);
        var recommendations = BuildRecommendations(profile);

        return new AiDatasetSummary
        {
            DatasetName = datasetName,
            Summary = summary,
            Insights = facts,
            Recommendations = recommendations,
            GeneratedByModel = false,
            Provider = "deterministic",
            Model = "rules-v1",
            Notice = "Generated from calculated dataset statistics. No language model was used.",
        };
    }

    public AiChatResponse AnswerQuestion(
        DatasetProfileResponse profile,
        string datasetName,
        AiChatRequest request,
        string context)
    {
        var question = request.Message.ToLowerInvariant();
        var facts = SelectFactsForQuestion(profile, question);
        var suggestions = SelectSuggestionsForQuestion(profile, question);
        var answer = ComposeAnswer(profile, question, facts);

        return new AiChatResponse
        {
            Answer = answer,
            Facts = facts,
            Suggestions = suggestions,
            GeneratedByModel = false,
            Provider = "deterministic",
            Model = "rules-v1",
            Notice = "Answered from the calculated dataset context using deterministic rules.",
        };
    }

    public AiDatasetSummary EnrichSummaryWithModel(
        DatasetProfileResponse profile,
        string datasetName,
        string modelOutput,
        string provider,
        string model)
    {
        var parsed = ModelOutputParser.TryParse(modelOutput);

        // Facts stay calculated. The model contributes narrative and suggestions only.
        var facts = BuildCoreFacts(profile);
        var recommendations = BuildRecommendations(profile);

        if (parsed is null)
        {
            return BuildSummary(profile, datasetName) with
            {
                Notice = $"The {provider} response could not be parsed, so the summary was "
                         + "produced from calculated statistics.",
            };
        }

        if (parsed.Suggestions.Count > 0)
        {
            recommendations = parsed.Suggestions
                .Concat(recommendations)
                .Take(8)
                .ToList();
        }

        return new AiDatasetSummary
        {
            DatasetName = datasetName,
            Summary = string.IsNullOrWhiteSpace(parsed.Summary)
                ? BuildSummary(profile, datasetName).Summary
                : parsed.Summary,
            Insights = facts,
            Recommendations = recommendations,
            GeneratedByModel = true,
            Provider = provider,
            Model = model,
            Notice = $"Narrative and suggestions generated by {provider} ({model}). "
                     + "All figures come from the deterministic analysis pipeline.",
        };
    }

    public AiChatResponse BuildChatResponse(
        DatasetProfileResponse profile,
        string datasetName,
        AiChatRequest request,
        string modelOutput,
        string provider,
        string model)
    {
        var parsed = ModelOutputParser.TryParse(modelOutput);
        var facts = SelectFactsForQuestion(profile, request.Message.ToLowerInvariant());
        var suggestions = SelectSuggestionsForQuestion(profile, request.Message.ToLowerInvariant());

        if (parsed is null)
        {
            return AnswerQuestion(profile, datasetName, request, string.Empty) with
            {
                Notice = $"The {provider} response could not be parsed; this answer was "
                         + "produced from calculated statistics.",
            };
        }

        // Prefer the model's suggestions, but keep the calculated facts list intact.
        if (parsed.Suggestions.Count > 0)
        {
            suggestions = parsed.Suggestions
                .Concat(suggestions)
                .Take(6)
                .ToList();
        }

        return new AiChatResponse
        {
            Answer = string.IsNullOrWhiteSpace(parsed.Answer)
                ? ComposeAnswer(profile, request.Message.ToLowerInvariant(), facts)
                : parsed.Answer,
            Facts = facts,
            Suggestions = suggestions,
            GeneratedByModel = true,
            Provider = provider,
            Model = model,
            Notice = $"Narrative generated by {provider} ({model}). Every figure above was "
                     + "calculated by the analysis pipeline, not by the model.",
        };
    }

    // ------------------------------------------------------------------ //
    // fact construction
    // ------------------------------------------------------------------ //

    private static List<AiInsight> BuildCoreFacts(DatasetProfileResponse profile)
    {
        var facts = new List<AiInsight>
        {
            new()
            {
                Title = "Dataset shape",
                Detail =
                    $"{N0(profile.RowCount)} rows across {N0(profile.ColumnCount)} columns "
                    + $"({N0(profile.TotalCells)} cells), occupying "
                    + $"{FormatBytes(profile.MemoryUsageBytes)} in memory.",
                Kind = "fact",
                Evidence =
                    $"{profile.RowCount} x {profile.ColumnCount} = {profile.TotalCells} cells",
            },
            new()
            {
                Title = "Completeness",
                Detail =
                    $"{N0(profile.TotalMissing)} cells are empty, which is "
                    + $"{P1(profile.OverallMissingPercentage)}% of the dataset.",
                Kind = "fact",
                Evidence =
                    $"{profile.TotalMissing} / {profile.TotalCells} cells = "
                    + $"{P1(profile.OverallMissingPercentage)}%",
            },
            new()
            {
                Title = "Row uniqueness",
                Detail = profile.DuplicateRowCount == 0
                    ? "Every row is distinct."
                    : $"{N0(profile.DuplicateRowCount)} duplicate rows were found "
                      + $"({P1(profile.DuplicatePercentage)}% of all rows).",
                Kind = "fact",
                Evidence = $"{profile.DuplicateRowCount} duplicates",
                Severity = profile.DuplicateRowCount == 0 ? "info" : "medium",
            },
        };

        if (profile.MlReadiness is { } readiness)
        {
            facts.Add(new AiInsight
            {
                Title = "ML readiness",
                Detail = readiness.Verdict,
                Kind = "fact",
                Evidence = $"score {I0(readiness.Overall)}/100 (grade {readiness.Grade}); "
                           + $"data quality {I0(readiness.DataQualityScore)}/100",
                Severity = ReadinessSeverity(readiness.Overall),
            });

            foreach (var gate in readiness.Gates)
            {
                facts.Add(new AiInsight
                {
                    Title = "Gating condition",
                    Detail = gate,
                    Kind = "fact",
                    Evidence = gate,
                    Severity = "high",
                });
            }

            foreach (var signal in readiness.LeakageSignals.Take(3))
            {
                facts.Add(new AiInsight
                {
                    Title = $"Target leakage risk: `{signal.Column}`",
                    Detail = signal.Rationale,
                    Kind = "fact",
                    Evidence = signal.Signal,
                    Column = signal.Column,
                    Severity = signal.Severity.ToLowerInvariant(),
                });
            }
        }

        var worstColumns = profile.Columns
            .Where(c => c.MissingPercentage > 0)
            .OrderByDescending(c => c.MissingPercentage)
            .Take(3);

        foreach (var column in worstColumns)
        {
            facts.Add(new AiInsight
            {
                Title = $"Missing values in `{column.Name}`",
                Detail =
                    $"{N0(column.NullCount)} of {N0(profile.RowCount)} rows are empty "
                    + $"({P1(column.MissingPercentage)}%).",
                Kind = "fact",
                Evidence = $"{column.NullCount} null of {column.NonNullCount + column.NullCount}",
                Column = column.Name,
                Severity = column.MissingPercentage >= 40
                    ? "high"
                    : column.MissingPercentage >= 15 ? "medium" : "low",
            });
        }

        return facts;
    }

    private static List<AiInsight> BuildRecommendations(DatasetProfileResponse profile)
    {
        var recommendations = new List<AiInsight>();

        foreach (var issue in profile.QualityIssues
                     .OrderBy(i => SeverityWeight(i.Severity))
                     .Take(6))
        {
            recommendations.Add(new AiInsight
            {
                Title = issue.Title,
                Detail = issue.Recommendation,
                Kind = "suggestion",
                Column = issue.Column,
                Severity = issue.Severity.ToLowerInvariant(),
            });
        }

        if (recommendations.Count == 0)
        {
            recommendations.Add(new AiInsight
            {
                Title = "No blocking issues detected",
                Detail = "This dataset passed every check. Proceed to exploratory analysis "
                         + "and establish a baseline model before investing in tuning.",
                Kind = "suggestion",
            });
        }

        return recommendations;
    }

    /// <summary>
    /// Routes a natural-language question to the facts that actually answer it, so
    /// the fallback is topic-aware rather than a generic dump.
    /// </summary>
    private static List<AiInsight> SelectFactsForQuestion(
        DatasetProfileResponse profile,
        string question)
    {
        var all = BuildCoreFacts(profile);

        if (question.Contains("problem") || question.Contains("wrong") ||
            question.Contains("issue") || question.Contains("quality"))
        {
            var problemFacts = profile.QualityIssues
                .OrderBy(i => SeverityWeight(i.Severity))
                .Take(4)
                .Select(issue => new AiInsight
                {
                    Title = issue.Title,
                    Detail = issue.Description,
                    Kind = "fact",
                    Evidence = issue.Code,
                    Column = issue.Column,
                    Severity = issue.Severity.ToLowerInvariant(),
                })
                .ToList();

            return problemFacts.Count > 0 ? problemFacts : all;
        }

        if (question.Contains("machine learning") || question.Contains("model") ||
            question.Contains("ready") || question.Contains("train"))
        {
            if (profile.MlReadiness is { } readiness)
            {
                return
                [
                    new AiInsight
                    {
                        Title = "ML readiness score",
                        Detail = readiness.Verdict,
                        Kind = "fact",
                        Evidence = $"{I0(readiness.Overall)}/100 (grade {readiness.Grade})",
                        Severity = ReadinessSeverity(readiness.Overall),
                    },
                    .. readiness.Components
                        .OrderBy(c => c.Score)
                        .Take(4)
                        .Select(c => new AiInsight
                        {
                            Title = $"{c.Label}: {I0(c.Score)}%",
                            Detail = c.Rationale,
                            Kind = "fact",
                            Evidence = $"{c.Key} = {P1(c.Score)} (weight {P2(c.Weight)})",
                            Severity = c.Score < 80 ? "medium" : "info",
                        }),
                    .. readiness.Gates.Select(g => new AiInsight
                    {
                        Title = "Gating condition",
                        Detail = g,
                        Kind = "fact",
                        Evidence = g,
                        Severity = "high",
                    }),
                ];
            }
        }

        if (question.Contains("leak") || question.Contains("leakage"))
        {
            var leakage = profile.MlReadiness?.LeakageSignals.ToList() ?? [];
            if (leakage.Count > 0)
            {
                return leakage
                    .Select(s => new AiInsight
                    {
                        Title = $"`{s.Column}`: {s.Signal}",
                        Detail = s.Rationale,
                        Kind = "fact",
                        Evidence = s.Signal,
                        Column = s.Column,
                        Severity = s.Severity.ToLowerInvariant(),
                    })
                    .ToList();
            }

            return
            [
                new AiInsight
                {
                    Title = "No leakage signals detected",
                    Detail =
                        "No duplicate columns, no near-perfect correlations between "
                        + "low-variance columns, and no post-outcome columns were found. "
                        + "This is a strong sign, though it depends on knowing which "
                        + "column is the target.",
                    Kind = "fact",
                    Evidence = "0 leakage signals",
                    Severity = "info",
                },
            ];
        }

        if (question.Contains("preprocess") || question.Contains("clean") ||
            question.Contains("impute") || question.Contains("prepare"))
        {
            return profile.QualityIssues
                .Where(i => i.Recommendation.Length > 0)
                .OrderBy(i => SeverityWeight(i.Severity))
                .Take(5)
                .Select(i => new AiInsight
                {
                    Title = $"Preprocessing: {i.Column ?? "dataset"}",
                    Detail = i.Recommendation,
                    Kind = "suggestion",
                    Column = i.Column,
                    Severity = i.Severity.ToLowerInvariant(),
                })
                .ToList();
        }

        if (question.Contains("column") || question.Contains("investigate"))
        {
            var interesting = profile.Columns
                .Where(c => c.MissingPercentage > 0 || c.Outliers.Count > 0 || c.IsConstant)
                .OrderByDescending(c => c.MissingPercentage)
                .Take(5);

            var columnFacts = interesting
                .Select(c => new AiInsight
                {
                    Title = c.Name,
                    Detail =
                        $"{c.InferredKind} column with {N0(c.NullCount)} missing "
                        + $"({P1(c.MissingPercentage)}%), {N0(c.UniqueCount)} distinct values.",
                    Kind = "fact",
                    Evidence = $"missing={c.NullCount}, unique={c.UniqueCount}",
                    Column = c.Name,
                })
                .ToList();

            return columnFacts.Count > 0 ? columnFacts : all;
        }

        if (question.Contains("pattern") || question.Contains("correlat") ||
            question.Contains("relationship"))
        {
            var pairs = profile.Correlations?.Pairs
                .Where(p => Math.Abs(p.Coefficient) >= 0.3)
                .Take(5)
                .Select(p => new AiInsight
                {
                    Title = $"{p.ColumnA} and {p.ColumnB}",
                    Detail = $"{P2(Math.Abs(p.Coefficient))} {Direction(p.Coefficient)} "
                             + "correlation between these two columns.",
                    Kind = "fact",
                    Evidence = $"r = {P4(p.Coefficient)}",
                    Column = p.ColumnA,
                })
                .ToList() ?? [];

            return pairs.Count > 0 ? pairs : all;
        }

        return all;
    }

    private static List<AiInsight> SelectSuggestionsForQuestion(
        DatasetProfileResponse profile,
        string question)
    {
        if (question.Contains("preprocess") || question.Contains("clean") ||
            question.Contains("impute"))
        {
            return BuildRecommendations(profile).Take(6).ToList();
        }

        return BuildRecommendations(profile).Take(4).ToList();
    }

    private static string ComposeAnswer(
        DatasetProfileResponse profile,
        string question,
        IReadOnlyList<AiInsight> facts)
    {
        var builder = new System.Text.StringBuilder();

        if (question.Contains("problem") || question.Contains("issue") ||
            question.Contains("wrong") || question.Contains("quality"))
        {
            builder.Append("The most significant problems are ");
            builder.Append(string.Join(
                ", ",
                facts.Take(3).Select(f => $"\"{f.Title}\"")));
            builder.Append(". ");
        }
        else if (question.Contains("machine learning") || question.Contains("ready") ||
                 question.Contains("model"))
        {
            if (profile.MlReadiness is { } readiness)
            {
                builder.Append(
                    $"This dataset scores {I0(readiness.Overall)}/100 for machine learning "
                    + $"readiness (grade {readiness.Grade}). {readiness.Verdict} ");

                var weakest = readiness.Components.OrderBy(c => c.Score).FirstOrDefault();
                if (weakest is not null)
                {
                    builder.Append(
                        $"The weakest dimension is {weakest.Label.ToLowerInvariant()} at "
                        + $"{I0(weakest.Score)}%. ");
                }
            }
        }
        else if (question.Contains("leak"))
        {
            builder.Append(
                facts.Count > 0
                    ? "There are leakage signals worth acting on. "
                    : "No target leakage signals were detected. ");
        }
        else if (question.Contains("preprocess") || question.Contains("clean"))
        {
            builder.Append(
                "Based on the detected issues, this is the preprocessing order I would use. ");
        }
        else
        {
            builder.Append(
                $"This dataset has {N0(profile.RowCount)} rows and {N0(profile.ColumnCount)} "
                + "columns. ");
        }

        var issues = profile.QualityIssues.Count;
        if (issues > 0)
        {
            builder.Append(
                $"{issues} quality issue{(issues == 1 ? " was" : "s were")} detected in total. ");
        }

        builder.Append("Every figure above was calculated directly from the dataset.");
        return builder.ToString();
    }

    // ------------------------------------------------------------------ //
    // helpers
    // ------------------------------------------------------------------ //

    private static string BuildStatisticsNarrative(DatasetProfileResponse profile)
    {
        var missingText = profile.TotalMissing == 0
            ? "There are no missing values."
            : $"Missingness is {P1(profile.OverallMissingPercentage)}% of all cells.";

        var duplicateText = profile.DuplicateRowCount == 0
            ? "No duplicate rows were detected."
            : $"{N0(profile.DuplicateRowCount)} rows are duplicated.";

        return $"{missingText} {duplicateText}";
    }

    private static string DescribeComposition(DatasetProfileResponse profile)
    {
        var numeric = profile.Columns.Count(c =>
            c.InferredKind is "numeric" or "integer");
        var categorical = profile.Columns.Count(c =>
            c.InferredKind is "categorical" or "boolean");
        var text = profile.Columns.Count(c => c.InferredKind == "text");
        var temporal = profile.Columns.Count(c => c.InferredKind == "datetime");

        var parts = new List<string>();
        if (numeric > 0) parts.Add($"{numeric} numeric");
        if (categorical > 0) parts.Add($"{categorical} categorical");
        if (text > 0) parts.Add($"{text} text");
        if (temporal > 0) parts.Add($"{temporal} date");

        return parts.Count == 0 ? "no typed columns detected" : string.Join(", ", parts);
    }

    private static string FormatBytes(long bytes) => bytes switch
    {
        < 1024 => $"{bytes} B",
        < 1024 * 1024 => $"{P1(bytes / 1024.0)} KB",
        < 1024L * 1024 * 1024 => $"{P1(bytes / (1024.0 * 1024))} MB",
        _ => $"{P2(bytes / (1024.0 * 1024 * 1024))} GB",
    };


    private static string Direction(double coefficient) =>
        coefficient >= 0 ? "positive" : "negative";

    // Every figure below is formatted invariantly on purpose. These strings are
    // product copy for an English-language product and are also read by a model, so
    // a machine locale such as es-ES must not render "1.000 rows" or "0,22" and change
    // what the numbers mean.
    private static string N0(long value) => value.ToString("N0", CultureInfo.InvariantCulture);

    private static string P1(decimal value) => value.ToString("0.0", CultureInfo.InvariantCulture);

    private static string P1(double value) => value.ToString("0.0", CultureInfo.InvariantCulture);

    private static string P2(decimal value) => value.ToString("0.00", CultureInfo.InvariantCulture);

    private static string P2(double value) => value.ToString("0.00", CultureInfo.InvariantCulture);

    private static string P4(double value) => value.ToString("0.0000", CultureInfo.InvariantCulture);

    private static string I0(decimal value) => value.ToString("0", CultureInfo.InvariantCulture);

    private static string ReadinessSeverity(decimal score) => score switch
    {
        >= 85 => "info",
        >= 70 => "low",
        >= 55 => "medium",
        _ => "high",
    };

    private static int SeverityWeight(string severity) => severity switch
    {
        "critical" => 0,
        "high" => 1,
        "medium" => 2,
        "low" => 3,
        _ => 4,
    };
}